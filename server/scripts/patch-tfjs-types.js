/**
 * Conditional TFJS type-augmentation generator.
 *
 * Background: @tensorflow/tfjs-core@4.x publishes a `dist/index.d.ts` entry in
 * package.json but the file is missing from some npm tarball extracts. Local
 * dev installs have been observed in two states:
 *   (a) types present  → real types fully resolve; our augmentation duplicates them.
 *   (b) types missing  → real types resolve to nothing; our augmentation must fill the gap.
 *
 * CI fresh installs land in state (a); some local installs land in state (b).
 * To keep both green this script writes `src/types/module-augmentations.ts`
 * conditionally at install time:
 *
 *   - State (a): writes a minimal stub (just `export {};`) so no duplicate
 *     identifier errors are produced.
 *   - State (b): writes the full augmentation so tsc has the surface it needs.
 *
 * The script reads from `src/types/module-augmentations.template.ts` (full
 * augmentation source-of-truth, NOT loaded by tsc directly) and emits to
 * `src/types/module-augmentations.ts` (the file tsc compiles).
 *
 * Wired in package.json `postinstall` after npm install / npm ci.
 */
const fs = require('fs');
const path = require('path');

const SERVER_ROOT = path.join(__dirname, '..');
const TFJS_CORE_DTS = path.join(SERVER_ROOT, 'node_modules', '@tensorflow', 'tfjs-core', 'dist', 'index.d.ts');
const AUGMENTATION_TARGET = path.join(SERVER_ROOT, 'src', 'types', 'module-augmentations.ts');
const AUGMENTATION_TEMPLATE = path.join(SERVER_ROOT, 'src', 'types', 'module-augmentations.template.ts');

const EMPTY_STUB = `/**
 * Module augmentations — generated by scripts/patch-tfjs-types.js.
 *
 * @tensorflow/tfjs-core types resolved cleanly in this install, so no manual
 * augmentation is needed. The full augmentation lives in
 * module-augmentations.template.ts and is emitted here only when the real
 * types are missing.
 */
export {};
`;

function writeIfChanged(target, content) {
  let prev = '';
  try { prev = fs.readFileSync(target, 'utf8'); } catch { /* missing */ }
  if (prev === content) {
    return false;
  }
  fs.writeFileSync(target, content);
  return true;
}

function main() {
  const tfjsTypesPresent = fs.existsSync(TFJS_CORE_DTS);

  if (tfjsTypesPresent) {
    const changed = writeIfChanged(AUGMENTATION_TARGET, EMPTY_STUB);
    if (changed) {
      console.log('[patch-tfjs-types] @tensorflow/tfjs-core types present — wrote empty stub.');
    } else {
      console.log('[patch-tfjs-types] @tensorflow/tfjs-core types present — stub already in place.');
    }
    return;
  }

  if (!fs.existsSync(AUGMENTATION_TEMPLATE)) {
    console.warn(`[patch-tfjs-types] Template missing at ${AUGMENTATION_TEMPLATE}; cannot generate full augmentation.`);
    // Still write the stub so tsc has a valid module file.
    writeIfChanged(AUGMENTATION_TARGET, EMPTY_STUB);
    return;
  }

  const template = fs.readFileSync(AUGMENTATION_TEMPLATE, 'utf8');
  const banner = `/**
 * Module augmentations — generated by scripts/patch-tfjs-types.js.
 *
 * @tensorflow/tfjs-core types were NOT present in this install; the full
 * augmentation below is the only source of TFJS types for tsc. To edit,
 * change src/types/module-augmentations.template.ts and re-run install.
 */
`;
  const out = banner + '\n' + template.replace(/^[\s\S]*?\/\*\*[\s\S]*?\*\/\s*/, '');
  const changed = writeIfChanged(AUGMENTATION_TARGET, out);
  if (changed) {
    console.log('[patch-tfjs-types] @tensorflow/tfjs-core types missing — wrote full augmentation.');
  } else {
    console.log('[patch-tfjs-types] @tensorflow/tfjs-core types missing — full augmentation already in place.');
  }
}

try {
  main();
} catch (err) {
  console.error('[patch-tfjs-types] Failed:', err && err.message ? err.message : err);
  process.exitCode = 1;
}
